"""Build a Windows executable of the target analyser into ./target.

Usage:  .venv\\Scripts\\python build_exe.py

Steps:
  1. byte-compile target_analyzer/ (fails early on syntax errors);
  2. write a small launcher to a temporary folder (not into the repo);
  3. run PyInstaller in one-folder, windowed mode.

Result: target\\TargetAnalyzer\\TargetAnalyzer.exe (the whole folder must be kept together).
"""
from __future__ import annotations

import compileall
import importlib.util
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PACKAGE = ROOT / "target_analyzer"
OUT_DIR = ROOT / "target"
APP_NAME = "TargetAnalyzer"

LAUNCHER = """\
# Launcher generated by build_exe.py: runs the same entry point as `python -m target_analyzer`.
from target_analyzer.__main__ import main

if __name__ == "__main__":
    main()
"""


def fail(message: str) -> None:
    print(f"ERROR: {message}", file=sys.stderr)
    sys.exit(1)


def check_compile() -> None:
    print("[1/3] Byte-compiling target_analyzer ...")
    if not compileall.compile_dir(str(PACKAGE), quiet=1, force=True):
        fail("syntax errors in target_analyzer (see messages above)")


def check_pyinstaller() -> None:
    if importlib.util.find_spec("PyInstaller") is None:
        fail("PyInstaller is not installed in this Python. Run: "
             "python -m pip install pyinstaller")


def build(workdir: Path, out_dir: Path) -> None:
    """Run PyInstaller; the app folder ends up in out_dir/APP_NAME."""
    print("[2/3] Writing launcher ...")
    launcher = workdir / f"{APP_NAME}_launcher.py"
    launcher.write_text(LAUNCHER, encoding="utf-8")

    print("[3/3] Running PyInstaller (this takes a few minutes) ...")
    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onedir",
        "--windowed",
        "--name", APP_NAME,
        "--distpath", str(out_dir),
        "--workpath", str(workdir / "build"),
        "--specpath", str(workdir),
        "--paths", str(ROOT),
        str(launcher),
    ]
    result = subprocess.run(cmd, cwd=ROOT)
    if result.returncode != 0:
        fail(f"PyInstaller exited with code {result.returncode}")


def main() -> None:
    check_compile()
    check_pyinstaller()

    # Remove only the previous dev build, never the versioned release folders.
    dev_dir = OUT_DIR / APP_NAME
    if dev_dir.exists():
        shutil.rmtree(dev_dir)
    OUT_DIR.mkdir(exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="build_exe_") as tmp:
        build(Path(tmp), OUT_DIR)

    exe = OUT_DIR / APP_NAME / f"{APP_NAME}.exe"
    if not exe.is_file():
        fail(f"expected executable not found: {exe}")
    print(f"Done: {exe}")
    print("Keep the whole folder together; run it with an optional database path argument.")


if __name__ == "__main__":
    main()
